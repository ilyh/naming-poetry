shijing_path = os.path.join(CHINESE_POETRY_REPO, '诗经', 'shijing.json')
if os.path.exists(shijing_path):
    data = load_json(shijing_path)
    for item in data:
        title = item.get('title', '无题')
        chapter = item.get('chapter', '')
        content_lines = item.get('content', [])
        if not content_lines:
            continue
        content = ''.join(content_lines)
        clean = content.replace('，','').replace('。','').replace('！','').replace('？','').replace('；','').replace('：','')
        if len(clean) < 4:
            continue
        poems.append({
            "title": f"{title}",
            "author": "佚名",
            "source": "shijing",
            "dynasty": "先秦",
            "content": content
        })
