def load_json(path):
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)

def is_good_poem(poem):
    """Filter out very long or very short poems"""
    paragraphs = poem.get('paragraphs', poem.get('content', []))
    text = ''.join(paragraphs)
    # Remove punctuation to count actual characters
    clean = text.replace('，','').replace('。','').replace('！','').replace('？','').replace('；','').replace('：','').replace('、','')
    return 8 <= len(clean) <= 200

def make_poem(title, author, source, dynasty, paragraphs):
    content = ''.join(paragraphs)
    return {
        "title": title,
        "author": author,
        "source": source,
        "dynasty": dynasty,
        "content": content
    }

